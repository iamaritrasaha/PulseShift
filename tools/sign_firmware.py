import argparse
import os
import sys
import zlib
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives.asymmetric.utils import decode_dss_signature, encode_dss_signature

TRAILER_MAGIC = b"PSOT" # PulseShift OTA
TRAILER_VERSION = 1
TRAILER_SIZE = 76 # 4 magic + 1 ver + 1 flags + 4 crc32 + 2 sig_len + 64 sig

def generate_key(key_path: str, public_header_path: str = None):
    os.makedirs(os.path.dirname(os.path.abspath(key_path)), exist_ok=True)
    if os.path.exists(key_path):
        print(f"Error: Key file already exists at '{key_path}'. Refusing to overwrite.", file=sys.stderr)
        sys.exit(1)

    private_key = ec.generate_private_key(ec.SECP256R1())
    pem_data = private_key.private_bytes(
        encoding=serialization.Encoding.PEM,
        format=serialization.PrivateFormat.PKCS8,
        encryption_algorithm=serialization.NoEncryption()
    )

    with open(key_path, "wb") as f:
        f.write(pem_data)
    print(f"Private signing key written to: {key_path}")
    print("CRITICAL: Keep this private key strictly outside git and secure.")

    public_key = private_key.public_key()
    pub_bytes = public_key.public_bytes(
        encoding=serialization.Encoding.X962,
        format=serialization.PublicFormat.UncompressedPoint
    )

    print(f"\nUncompressed Public Key (65 bytes):")
    print(pub_bytes.hex())

    header_content = (
        "// PulseShift Trusted OTA Public Key (NIST P-256 / secp256r1 uncompressed SEC1)\n"
        "// Auto-generated by tools/sign_firmware.py. Safe to commit (public key only).\n"
        "#pragma once\n"
        "#include <stdint.h>\n\n"
        "static const uint8_t PULSESHIFT_OTA_PUBLIC_KEY[65] = {\n  "
        + ", ".join(f"0x{b:02X}" for b in pub_bytes)
        + "\n};\n"
    )

    if public_header_path:
        with open(public_header_path, "w") as f:
            f.write(header_content)
        print(f"Public key C header written to: {public_header_path}")
    else:
        print("\nC Header Snippet:")
        print(header_content)

def sign_binary(key_path: str, input_bin: str, output_bin: str):
    if not os.path.exists(key_path):
        print(f"Error: Private key not found at '{key_path}'.", file=sys.stderr)
        sys.exit(1)
    if not os.path.exists(input_bin):
        print(f"Error: Input binary not found at '{input_bin}'.", file=sys.stderr)
        sys.exit(1)

    with open(key_path, "rb") as f:
        private_key = serialization.load_pem_private_key(f.read(), password=None)

    with open(input_bin, "rb") as f:
        image_data = f.read()

    # Safety: check image magic
    if len(image_data) < 1 or image_data[0] != 0xE7:
        print(f"Warning: Binary magic byte is 0x{image_data[0]:02X}, expected 0xE7 (ESP32 image).", file=sys.stderr)

    # Compute CRC32
    crc32_val = zlib.crc32(image_data) & 0xFFFFFFFF

    # Compute SHA-256
    digest = hashes.Hash(hashes.SHA256())
    digest.update(image_data)
    sha256_bytes = digest.finalize()

    # Sign SHA-256 digest
    der_signature = private_key.sign(sha256_bytes, ec.ECDSA(hashes.SHA256()))
    r, s = decode_dss_signature(der_signature)

    r_bytes = r.to_bytes(32, byteorder="big")
    s_bytes = s.to_bytes(32, byteorder="big")
    raw_signature = r_bytes + s_bytes

    # Build 76-byte trailer:
    # 4 bytes magic: PSOT
    # 1 byte ver: 1
    # 1 byte flags: 0
    # 4 bytes crc32 (little endian)
    # 2 bytes sig_len (little endian, 64)
    # 64 bytes raw sig (r[32] || s[32])
    trailer = bytearray()
    trailer.extend(TRAILER_MAGIC)
    trailer.append(TRAILER_VERSION)
    trailer.append(0) # flags
    trailer.extend(crc32_val.to_bytes(4, byteorder="little"))
    trailer.extend((64).to_bytes(2, byteorder="little"))
    trailer.extend(raw_signature)

    assert len(trailer) == TRAILER_SIZE, f"Trailer size mismatch: {len(trailer)} != {TRAILER_SIZE}"

    signed_data = image_data + trailer
    with open(output_bin, "wb") as f:
        f.write(signed_data)

    print("=== Firmware Signing Succeeded ===")
    print(f"Payload Size   : {len(image_data)} bytes")
    print(f"Total Package  : {len(signed_data)} bytes (includes {TRAILER_SIZE}-byte PSOT trailer)")
    print(f"CRC32          : 0x{crc32_val:08X}")
    print(f"SHA-256        : {sha256_bytes.hex()}")
    print(f"ECDSA Signature: {raw_signature.hex()[:32]}...{raw_signature.hex()[-32:]}")
    print(f"Signed Image   : {output_bin}")

def verify_binary(pubkey_input: str, input_bin: str):
    if not os.path.exists(input_bin):
        print(f"Error: Input binary not found at '{input_bin}'.", file=sys.stderr)
        sys.exit(1)

    # Load public key
    if os.path.exists(pubkey_input):
        with open(pubkey_input, "rb") as f:
            data = f.read()
            if b"BEGIN PUBLIC KEY" in data:
                public_key = serialization.load_pem_public_key(data)
            else:
                public_key = ec.EllipticCurvePublicKey.from_encoded_point(ec.SECP256R1(), data)
    else:
        # Try raw hex (65 bytes uncompressed: 130 hex chars)
        raw_bytes = bytes.fromhex(pubkey_input.strip())
        public_key = ec.EllipticCurvePublicKey.from_encoded_point(ec.SECP256R1(), raw_bytes)

    with open(input_bin, "rb") as f:
        file_data = f.read()

    if len(file_data) < TRAILER_SIZE:
        print(f"Error: File is smaller than minimum trailer size ({len(file_data)} < {TRAILER_SIZE}).", file=sys.stderr)
        sys.exit(1)

    trailer = file_data[-TRAILER_SIZE:]
    image_data = file_data[:-TRAILER_SIZE]

    magic = trailer[:4]
    if magic != TRAILER_MAGIC:
        print(f"Error: Invalid trailer magic: {magic!r}. Expected {TRAILER_MAGIC!r}.", file=sys.stderr)
        sys.exit(1)

    version = trailer[4]
    crc32_expected = int.from_bytes(trailer[6:10], byteorder="little")
    sig_len = int.from_bytes(trailer[10:12], byteorder="little")
    raw_signature = trailer[12:12+sig_len]

    # Verify CRC32
    crc32_actual = zlib.crc32(image_data) & 0xFFFFFFFF
    if crc32_actual != crc32_expected:
        print(f"FAILED: CRC32 mismatch! Expected 0x{crc32_expected:08X}, calculated 0x{crc32_actual:08X}.", file=sys.stderr)
        sys.exit(2)

    # Verify SHA-256 and ECDSA
    r = int.from_bytes(raw_signature[:32], byteorder="big")
    s = int.from_bytes(raw_signature[32:64], byteorder="big")
    der_signature = encode_dss_signature(r, s)

    digest = hashes.Hash(hashes.SHA256())
    digest.update(image_data)
    sha256_bytes = digest.finalize()

    try:
        public_key.verify(der_signature, sha256_bytes, ec.ECDSA(hashes.SHA256()))
        print("VERIFICATION SUCCESS: Signature, CRC32, and SHA-256 are valid and trusted.")
        print(f"Payload Size: {len(image_data)} bytes")
        print(f"CRC32       : 0x{crc32_actual:08X}")
        print(f"SHA-256     : {sha256_bytes.hex()}")
    except Exception as e:
        print(f"FAILED: Cryptographic signature verification failed: {e}", file=sys.stderr)
        sys.exit(3)

def main():
    parser = argparse.ArgumentParser(description="PulseShift Firmware Signing and Integrity Utility")
    subparsers = parser.add_subparsers(dest="command", required=True)

    gen_p = subparsers.add_parser("generate-key", help="Generate a new NIST P-256 ECDSA keypair")
    gen_p.add_argument("--key", required=True, help="Output path for private PEM key")
    gen_p.add_argument("--header", help="Output path for C header file with public key")

    sign_p = subparsers.add_parser("sign", help="Sign a firmware binary with ECDSA P-256")
    sign_p.add_argument("--key", required=True, help="Path to private PEM key")
    sign_p.add_argument("--input", required=True, help="Input firmware binary (.bin)")
    sign_p.add_argument("--output", required=True, help="Output signed binary (.signed.bin)")

    verify_p = subparsers.add_parser("verify", help="Verify a signed firmware binary")
    verify_p.add_argument("--public-key", required=True, help="Path to public key or 130-char hex string")
    verify_p.add_argument("--input", required=True, help="Input signed binary")

    args = parser.parse_args()
    if args.command == "generate-key":
        generate_key(args.key, args.header)
    elif args.command == "sign":
        sign_binary(args.key, args.input, args.output)
    elif args.command == "verify":
        verify_binary(args.public_key, args.input)

if __name__ == "__main__":
    main()
